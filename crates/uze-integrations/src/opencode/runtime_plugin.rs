//! UZE's one plugin in OpenCode's global plugin directory, which carries
//! every capability UZE delivers there that needs code inside the harness.
//!
//! OpenCode V2 sets each plugin up once per location its shared background
//! service serves, and hands it that location (measured on 2.1.2,
//! `experiments/opencode/project-agents-plugin`), so one file serves every
//! project and every launch. Each section sets itself up on its own: one
//! that throws costs only itself, never another section.
//!
//! The file is UZE's by its first line. A file at its path that does not
//! carry that line is the operator's and is never written over; what UZE
//! would have delivered through it is then reported blocked by that file.

use std::{
    fs,
    path::{Path, PathBuf},
};

use uze_core::{Result, UzeError};

/// The plugin's file in OpenCode's global plugin directory.
pub(crate) const FILE: &str = "uze.ts";

/// The first line of the plugin: what tells UZE the file is its own.
const OWNED: &str = "// Generated by UZE: what UZE delivers to OpenCode, as one plugin.";

/// Files earlier releases wrote in the plugin directory, each with the
/// first line that proves the file there is still one of them. Setup takes
/// out the ones that do; the rest are the operator's.
const RETIRED: &[(&str, &str)] = &[
    (
        "uze-agent-context.ts",
        "// Generated by UZE: gives agents UZE launched their context.",
    ),
    (
        crate::rules::plugin::RETIRED_FILE,
        crate::rules::plugin::HEADER,
    ),
];

/// One part of the plugin: its name, which the plugin reports a failure
/// under, and a JavaScript expression evaluating to `async (ctx) => ...`,
/// which may return a cleanup.
pub(crate) struct Section {
    pub(crate) name: &'static str,
    pub(crate) source: String,
}

/// Whether the plugin UZE would write is the one OpenCode loads.
#[derive(Clone, Debug, Eq, PartialEq)]
pub(super) enum PluginState {
    Installed,
    /// Not there, or an earlier version of UZE's: setup writes it.
    Missing,
    /// A file UZE did not write holds the plugin's path.
    Foreign(PathBuf),
}

pub(crate) fn path(config_root: &Path) -> PathBuf {
    config_root.join("plugins").join(FILE)
}

/// The plugin carrying `sections`, in order.
pub(crate) fn source(sections: &[Section]) -> String {
    let entries: String = sections
        .iter()
        .map(|section| {
            format!(
                "  [{}, {}],\n",
                serde_json::to_string(section.name).expect("a name serializes"),
                section.source.trim()
            )
        })
        .collect();
    format!(
        r#"{OWNED}
// Written again by `uze setup`; an edit here does not survive it.
import {{ existsSync, lstatSync, readdirSync, readFileSync, watch }} from "node:fs";
import {{ basename, join }} from "node:path";
import {{ homedir }} from "node:os";

const SECTIONS = [
{entries}];

export default {{
  id: "uze",
  async setup(ctx) {{
    const cleanups = [];
    for (const [name, section] of SECTIONS) {{
      try {{
        const cleanup = await section(ctx);
        if (typeof cleanup === "function") cleanups.push(cleanup);
      }} catch (error) {{
        console.error(`uze ${{name}}: ${{error}}`);
      }}
    }}
    return () => {{
      for (const cleanup of cleanups) {{
        try {{
          cleanup();
        }} catch {{}}
      }}
    }};
  }},
}};
"#
    )
}

/// Where the plugin stands against `wanted`.
pub(super) fn state(config_root: &Path, wanted: &str) -> PluginState {
    let path = path(config_root);
    match fs::read_to_string(&path) {
        Ok(current) if current == wanted => PluginState::Installed,
        Ok(current) if !current.starts_with(OWNED) => PluginState::Foreign(path),
        _ => PluginState::Missing,
    }
}

/// Writes `wanted` when the plugin is missing or is an earlier version of
/// UZE's, and takes out the files earlier releases wrote in its place. A
/// file UZE did not write is left alone.
pub(super) fn ensure(config_root: &Path, wanted: &str) -> Result<()> {
    retire(config_root)?;
    if state(config_root, wanted) != PluginState::Missing {
        return Ok(());
    }
    let path = path(config_root);
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).map_err(UzeError::write(parent))?;
    }
    fs::write(&path, wanted).map_err(UzeError::write(&path))
}

fn retire(config_root: &Path) -> Result<()> {
    for (name, header) in RETIRED {
        let path = config_root.join("plugins").join(name);
        if fs::read_to_string(&path).is_ok_and(|current| current.starts_with(header)) {
            fs::remove_file(&path).map_err(UzeError::write(&path))?;
        }
    }
    Ok(())
}

/// Why something delivered through the plugin cannot reach OpenCode, in
/// words naming `what`; `None` when it can.
pub(super) fn shortfall(config_root: &Path, wanted: &str, what: &str) -> Option<String> {
    match state(config_root, wanted) {
        PluginState::Installed => None,
        PluginState::Foreign(path) => Some(format!(
            "{} is not UZE's plugin, so {what} cannot reach OpenCode",
            path.display()
        )),
        PluginState::Missing => {
            Some("UZE's OpenCode plugin is not installed yet; `uze setup` installs it".to_owned())
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sections() -> Vec<Section> {
        vec![Section {
            name: "demo",
            source: "async (ctx) => {}".to_owned(),
        }]
    }

    #[test]
    fn the_plugin_is_written_refreshed_and_never_over_a_foreign_file() {
        let root = uze_testkit::temp::scratch("opencode-runtime-plugin");
        let wanted = source(&sections());
        assert_eq!(state(&root, &wanted), PluginState::Missing);

        ensure(&root, &wanted).unwrap();
        assert_eq!(state(&root, &wanted), PluginState::Installed);

        let newer = source(&[Section {
            name: "demo",
            source: "async (ctx) => { return () => {}; }".to_owned(),
        }]);
        assert_eq!(
            state(&root, &newer),
            PluginState::Missing,
            "an older one of UZE's"
        );
        ensure(&root, &newer).unwrap();
        assert_eq!(fs::read_to_string(path(&root)).unwrap(), newer);

        fs::write(path(&root), "// the operator's own plugin").unwrap();
        ensure(&root, &wanted).unwrap();
        assert_eq!(
            fs::read_to_string(path(&root)).unwrap(),
            "// the operator's own plugin"
        );
        assert_eq!(state(&root, &wanted), PluginState::Foreign(path(&root)));
        assert!(
            shortfall(&root, &wanted, "x")
                .unwrap()
                .contains("is not UZE's plugin")
        );
        let _ = fs::remove_dir_all(root);
    }

    #[test]
    fn setup_takes_out_only_the_earlier_files_that_are_still_uzes() {
        let root = uze_testkit::temp::scratch("opencode-runtime-plugin-retire");
        let plugins = root.join("plugins");
        fs::create_dir_all(&plugins).unwrap();
        let (name, header) = RETIRED[0];
        fs::write(
            plugins.join(name),
            format!("{header}\nexport default {{}};\n"),
        )
        .unwrap();
        ensure(&root, &source(&sections())).unwrap();
        assert!(
            !plugins.join(name).exists(),
            "an earlier release's file is retired"
        );

        fs::write(plugins.join(name), "// someone else's file of that name").unwrap();
        ensure(&root, &source(&sections())).unwrap();
        assert!(
            plugins.join(name).exists(),
            "a file of the same name UZE did not write stays"
        );
        let _ = fs::remove_dir_all(root);
    }

    #[test]
    fn a_section_that_throws_costs_only_itself() {
        let Some(bun) = crate::opencode::bun_for_tests() else {
            return;
        };
        let root = uze_testkit::temp::scratch("opencode-runtime-plugin-isolation");
        fs::create_dir_all(&root).unwrap();
        fs::write(
            root.join("uze.ts"),
            source(&[
                Section {
                    name: "broken",
                    source: "async (ctx) => { throw new Error(\"boom\"); }".to_owned(),
                },
                Section {
                    name: "working",
                    source: "async (ctx) => { ctx.reached = true; }".to_owned(),
                },
            ]),
        )
        .unwrap();
        fs::write(
            root.join("drive.ts"),
            r#"import plugin from "./uze.ts";
const errors = [];
console.error = (...parts) => errors.push(parts.join(" "));
const ctx = {};
await plugin.setup(ctx);
console.log(JSON.stringify({ reached: ctx.reached === true, errors }));
"#,
        )
        .unwrap();
        let output = std::process::Command::new(bun)
            .args(["run", "drive.ts"])
            .current_dir(&root)
            .output()
            .unwrap();
        assert!(
            output.status.success(),
            "{}",
            String::from_utf8_lossy(&output.stderr)
        );
        let reported: serde_json::Value =
            serde_json::from_slice(output.stdout.trim_ascii()).unwrap();
        assert_eq!(reported["reached"], true, "the next section still sets up");
        assert!(
            reported["errors"][0]
                .as_str()
                .unwrap()
                .contains("uze broken: Error: boom"),
            "{reported}"
        );
        let _ = fs::remove_dir_all(root);
    }
}
