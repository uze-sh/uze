//! The agent's context on OpenCode: a plugin UZE installs once, whose
//! `session.hook("context")` pushes onto the request's system parts the
//! document UZE wrote for that conversation.
//!
//! One shared background server serves every OpenCode launch and keeps the
//! environment and configuration of whichever launch started it, so nothing
//! can be handed to it per launch. What it does see is the conversation:
//! UZE assigns the session id before the launch, writes the document under
//! that id, and the plugin — found in the auto-discovered global plugins
//! directory, loaded by a running server without a restart — reads it on
//! every request. A conversation UZE did not launch has no document and is
//! given nothing.
//!
//! Measured on 2.0.31 (`experiments/opencode/agent-context`): the document
//! lands in a `system` part, a resumed process reads the current one, and
//! no copy is kept in the conversation (`opencode session export` holds
//! none).

use std::{
    fs,
    path::{Path, PathBuf},
};

use uze_core::{
    Result, UzeError,
    integration::{AgentContext, ContextContribution},
};

use crate::shared::agent_context::write_private;

/// The plugin's file in OpenCode's global plugins directory.
pub(super) const PLUGIN_FILE: &str = "uze-agent-context.ts";

/// The first line of the plugin, which is how UZE knows the file at that
/// path is its own to replace: a file there that does not carry it is the
/// operator's and is never written over.
const OWNED: &str = "// Generated by UZE: gives agents UZE launched their context.";

pub(super) fn plugin_path(config_root: &Path) -> PathBuf {
    config_root.join("plugins").join(PLUGIN_FILE)
}

/// The plugin, reading documents from `dir`. The directory is written into
/// the source rather than read from the environment, because the shared
/// server's environment is not the launch's.
pub(super) fn plugin_source(dir: &Path) -> String {
    let dir = serde_json::to_string(&dir.to_string_lossy()).expect("a path serializes");
    format!(
        r#"{OWNED}
import {{ existsSync, readFileSync }} from "node:fs";
import {{ join }} from "node:path";

const DIR = {dir};

export default {{
  id: "uze-agent-context",
  async setup(ctx) {{
    await ctx.session.hook("context", async (event) => {{
      if (!event.sessionID || !Array.isArray(event.system)) return;
      const file = join(DIR, `${{event.sessionID}}.md`);
      if (!existsSync(file)) return;
      const text = readFileSync(file, "utf8");
      const first = event.system[0];
      event.system.push(typeof first === "object" && first !== null ? {{ ...first, text }} : text);
    }});
  }},
}};
"#
    )
}

/// Writes the plugin when it is missing or is UZE's and out of date. A file
/// at that path UZE did not write is left alone.
pub(super) fn ensure_plugin(config_root: &Path, dir: &Path) -> Result<()> {
    let path = plugin_path(config_root);
    let wanted = plugin_source(dir);
    match fs::read_to_string(&path) {
        Ok(current) if current == wanted => return Ok(()),
        Ok(current) if !current.starts_with(OWNED) => return Ok(()),
        _ => {}
    }
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).map_err(UzeError::write(parent))?;
    }
    fs::write(&path, wanted).map_err(UzeError::write(&path))
}

/// Why the channel cannot reach this machine's OpenCode: the plugin is not
/// there, or the file in its place is not UZE's.
pub(super) fn unavailable(config_root: &Path, dir: &Path) -> Option<String> {
    let path = plugin_path(config_root);
    match fs::read_to_string(&path) {
        Ok(current) if current == plugin_source(dir) => None,
        Ok(current) if !current.starts_with(OWNED) => Some(format!(
            "{} is not UZE's plugin, so this agent's context cannot reach OpenCode",
            path.display()
        )),
        _ => Some("UZE's OpenCode plugin is not installed yet; `uze setup` installs it".to_owned()),
    }
}

/// Writes the document under the conversation UZE assigned this launch.
pub(super) fn deliver(dir: &Path, ctx: &AgentContext) -> Result<ContextContribution> {
    let Some(session) = ctx.session else {
        return Ok(ContextContribution::default());
    };
    write_private(&dir.join(format!("{}.md", session.as_str())), ctx.text)?;
    Ok(ContextContribution::default())
}

/// Removes the conversation's document, so the plugin gives it nothing.
pub(super) fn withdraw(dir: &Path, session: Option<&uze_core::session::SessionId>) {
    if let Some(session) = session {
        let _ = fs::remove_file(dir.join(format!("{}.md", session.as_str())));
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use uze_core::session::SessionId;

    #[test]
    fn the_plugin_is_installed_refreshed_and_never_written_over_a_foreign_file() {
        let root = uze_testkit::temp::scratch("opencode-agent-context-plugin");
        let dir = root.join("sessions");
        assert!(unavailable(&root, &dir).is_some());

        ensure_plugin(&root, &dir).unwrap();
        assert!(unavailable(&root, &dir).is_none());
        let source = fs::read_to_string(plugin_path(&root)).unwrap();
        assert!(source.contains("session.hook(\"context\""));
        assert!(source.contains(&*dir.to_string_lossy()));

        let moved = root.join("elsewhere");
        ensure_plugin(&root, &moved).unwrap();
        assert!(
            fs::read_to_string(plugin_path(&root))
                .unwrap()
                .contains("elsewhere")
        );

        fs::write(plugin_path(&root), "// the operator's own plugin").unwrap();
        ensure_plugin(&root, &dir).unwrap();
        assert_eq!(
            fs::read_to_string(plugin_path(&root)).unwrap(),
            "// the operator's own plugin"
        );
        assert!(unavailable(&root, &dir).is_some());
        let _ = fs::remove_dir_all(root);
    }

    #[test]
    fn the_document_is_written_under_the_assigned_conversation() {
        let root = uze_testkit::temp::scratch("opencode-agent-context-deliver");
        let session = SessionId::new("ses_abc");
        let contribution = deliver(
            &root,
            &AgentContext {
                dir: &root.join("agent"),
                file: &root.join("agent").join("context.md"),
                text: "facts",
                launch: "l",
                session: Some(&session),
            },
        )
        .unwrap();
        assert_eq!(
            contribution,
            ContextContribution::default(),
            "nothing in argv or env"
        );
        assert_eq!(
            fs::read_to_string(root.join("ses_abc.md")).unwrap(),
            "facts"
        );
        withdraw(&root, Some(&session));
        assert!(
            !root.join("ses_abc.md").exists(),
            "a launch with nothing to give leaves nothing behind"
        );
        let _ = fs::remove_dir_all(root);
    }
}
