//! What the OpenCode integration does only because an earlier release left
//! it in OpenCode's own configuration (the `earlier-releases` rule): plugin
//! files of their own that one plugin now carries. Each is retired where it
//! always was — setup, and the inspection and detach of a receipt — reading
//! what it handles from here.

use std::path::{Path, PathBuf};

use uze_core::document::earlier::{Earlier, Lasts};

/// The file an earlier release wrote the rules plugin to, by itself.
pub(crate) const RETIRED_RULES_FILE: &str = "uze-rules.ts";

/// Files earlier releases wrote in the plugin directory, each with the
/// first line that proves the file there is still one of them. Setup takes
/// out the ones that do; the rest are the operator's.
pub(crate) const RETIRED_PLUGIN_FILES: &[(&str, &str)] = &[
    (
        "uze-agent-context.ts",
        "// Generated by UZE: gives agents UZE launched their context.",
    ),
    (
        RETIRED_RULES_FILE,
        "// Generated rules plugin — do not edit; it is written again.",
    ),
];

/// This vertical's entries. Setup retires the plugin files on every run
/// that reaches it, and a hook bridge goes when its package is next
/// attached or detached: none is bounded yet.
pub(crate) fn earlier() -> Vec<Earlier> {
    vec![
        Earlier {
            name: "OpenCode plugin files of their own, now sections of one plugin",
            lasts: Lasts::Unbounded,
            spelled: &["uze-agent-context.ts", RETIRED_RULES_FILE],
            site: file!(),
        },
        Earlier {
            name: "OpenCode hook bridges, one plugin per package",
            lasts: Lasts::Unbounded,
            spelled: &[],
            site: file!(),
        },
    ]
}

/// Where an earlier release delivered a package's hooks, as a plugin of its
/// own: `<config root>/plugins/hooks-<package>.ts`. Read only to inspect,
/// detach and replace what such a release left.
/// `<config root>/plugins/` is OpenCode's documented global plugin directory
/// (`~/.config/opencode/plugins/`), auto-discovered at startup — the file is
/// therefore the single, self-contained load source: no `plugin` entry in
/// `opencode.json` exists to duplicate it. (Verified against the real
/// harness: the legacy `.opencode/plugins/` path is project-scoped and NOT
/// auto-discovered under the global config directory.)
pub(crate) fn hook_bridge_path(config_root: &Path, package_id: &str) -> PathBuf {
    config_root
        .join("plugins")
        .join(format!("hooks-{package_id}.ts"))
}
